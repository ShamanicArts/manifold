import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
const requireFromWeb = createRequire(new URL('../web/package.json', import.meta.url));
const { chromium } = requireFromWeb('playwright-core');
const browser = await chromium.launch({ executablePath: process.env.MANIFOLD_CHROMIUM ?? '/usr/bin/chromium',
  headless: true, args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${process.env.MANIFOLD_SITE_URL ?? 'http://127.0.0.1:4173'}/main-looper.html`);
  assert.equal(await page.locator('.layer').count(), 4);
  assert.equal(await page.locator('.segment').count(), 9);
  await page.locator('#source').selectOption('oscillator');
  await page.locator('#audio-button').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Running'), { timeout: 25000 });
  await page.locator('#rec').click();
  await page.waitForFunction(() => document.querySelector('#rec').textContent.includes('REC*'));
  await page.waitForTimeout(1000);
  await page.locator('#rec').click();
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="0"] .state').textContent === 'Playing', { timeout: 10000 });
  await page.locator('#sample-bars').focus();
  await page.keyboard.press('Home');
  await page.locator('#sample-cap').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Live sample captured'), { timeout: 15000 });
  assert.notEqual(await page.locator('#sample-length').textContent(), '0ms');
  assert.equal(await page.locator('#sample-blend').getAttribute('aria-valuenow'), '1');
  await page.waitForFunction(() => {
    const canvas = document.querySelector('#source-graph');
    const pixels = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
    let marked = 0;
    for (let offset = 0; offset < pixels.length; offset += 4) {
      if (pixels[offset] === 34 && pixels[offset + 1] === 211 && pixels[offset + 2] === 238) marked++;
    }
    return marked > 100;
  }, { timeout: 3000 });
  await page.screenshot({ path: new URL('../web/public/main-live-sample.png', import.meta.url).pathname, fullPage: true });
  await page.locator('.source-module').screenshot({ path: new URL('../web/public/main-source-panel.png', import.meta.url).pathname });
  await page.locator('#sample-source-select').selectOption('1');
  await page.locator('#sample-cap').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('L1 sample captured'), { timeout: 15000 });
  await page.screenshot({ path: new URL('../web/public/main-layer-sample.png', import.meta.url).pathname, fullPage: true });
  await page.locator('#sample-mode').click();
  assert.equal(await page.locator('#sample-mode').textContent(), 'Free');
  await page.locator('#sample-cap').click();
  await page.waitForFunction(() => document.querySelector('#sample-cap').textContent === 'STOP');
  await page.waitForTimeout(240);
  await page.screenshot({ path: new URL('../web/public/main-free-recording.png', import.meta.url).pathname, fullPage: true });
  await page.locator('#sample-cap').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('L1 Free sample captured'), { timeout: 15000 });
  assert.ok(Number.parseInt(await page.locator('#sample-length').textContent(), 10) >= 150);
  await page.screenshot({ path: new URL('../web/public/main-free-sample.png', import.meta.url).pathname, fullPage: true });
  await page.locator('#sample-mode').click();
  await page.locator('#sample-pitch-mode [data-value="1"]').click();
  assert.equal(await page.locator('#sample-stretch').isVisible(), true);
  await page.locator('#sample-pitch-mode [data-value="0"]').click();
  await page.locator('[data-source-tab="wave"]').click();
  await page.locator('#synth-wave').selectOption('1');
  await page.locator('#wave-render-mode [data-value="1"]').click();
  assert.equal(await page.locator('#wave-render-mode [aria-pressed="true"]').getAttribute('data-value'), '1');
  assert.equal(await page.locator('[data-source-tab="wave"]').getAttribute('aria-selected'), 'true');
  await page.locator('[data-source-tab="blend"]').click();
  assert.equal(await page.locator('#blend-keytrack [aria-pressed="true"]').getAttribute('data-value'), '2');
  await page.locator('#blend-keytrack [data-value="1"]').click();
  assert.equal(await page.locator('#blend-keytrack [aria-pressed="true"]').getAttribute('data-value'), '1');
  await page.locator('[data-source-tab="sample"]').click();
  const inferredTempo = Number(await page.locator('#tempo').inputValue());
  assert.ok(inferredTempo > 90 && inferredTempo < 160, `First Loop tempo: ${inferredTempo}`);
  await page.locator('.donut').nth(1).click();
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="1"]').classList.contains('active'));
  await page.locator('.segment').nth(6).click(); // recent 1/4 bar to layer 1
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="1"] .state').textContent === 'Playing', { timeout: 10000 });
  assert.match(await page.locator('.layer[data-layer="1"] .bars').textContent(), /1\/4 bar/);
  await page.locator('#mode').selectOption('2');
  await page.locator('.segment').nth(7).click();
  await page.waitForFunction(() => !document.querySelector('#fire').hidden);
  await page.locator('#fire').click();
  await page.waitForFunction(() => document.querySelector('#fire').hidden);
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="1"] .state').textContent === 'Playing');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#save-session').click();
  const download = await downloadPromise;
  const bundle = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(bundle.id, 'manifold.main-looper');
  assert.ok(bundle.layers[0].frames > 0 && bundle.layers[1].frames > 0);
  await page.locator('#audio-button').click();
  await page.locator('#audio-button').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Running'));
  await page.locator('#open-session').setInputFiles({ name: 'main-looper.json',
    mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bundle)) });
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Opened the four-layer'), { timeout: 15000 });
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="0"] .bars').textContent.includes('bar')
    && document.querySelector('.layer[data-layer="1"] .bars').textContent.includes('bar'));
  assert.match(await page.locator('.layer[data-layer="0"] .bars').textContent(), /bar/);
  assert.match(await page.locator('.layer[data-layer="1"] .bars').textContent(), /bar/);
  const wave = await page.locator('.layer[data-layer="0"] .wave').boundingBox();
  await page.mouse.move(wave.x + wave.width * .6, wave.y + wave.height * .5);
  await page.mouse.down();
  await page.mouse.move(wave.x + wave.width * .4, wave.y + wave.height * .5, { steps: 8 });
  await page.waitForFunction(() => Number(document.querySelectorAll('.layer[data-layer="0"] .knob')[1].dataset.value) < 0);
  await page.mouse.up();
  await page.waitForFunction(() => Number(document.querySelectorAll('.layer[data-layer="0"] .knob')[1].dataset.value) > 0);
  await page.locator('#audio-button').click();
  const frames = 48_000, wav = Buffer.alloc(44 + frames * 2);
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(48_000, 24); wav.writeUInt32LE(96_000, 28);
  wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36);
  wav.writeUInt32LE(frames * 2, 40);
  for (let frame = 0; frame < frames; frame++) wav.writeInt16LE(Math.round(Math.sin(frame * 2 * Math.PI * 220 / 48_000) * 8000), 44 + frame * 2);
  await page.locator('#source').selectOption('file');
  await page.locator('#file').setInputFiles({ name: 'tone.wav', mimeType: 'audio/wav', buffer: wav });
  await page.locator('#audio-button').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('looping audio file'));
  await page.locator('#mode').selectOption('0');
  await page.waitForTimeout(150);
  await page.locator('.segment').nth(8).click();
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="0"] .state').textContent === 'Playing');
  await page.locator('#audio-button').click();
  await page.locator('#source').selectOption('none');
  await page.locator('#audio-button').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Main voice bank'));
  const key = await page.locator('.synth-key').first().boundingBox();
  await page.mouse.move(key.x + key.width / 2, key.y + key.height / 2);
  await page.mouse.down();
  await page.waitForTimeout(500);
  await page.mouse.up();
  await page.locator('.donut').nth(2).click();
  await page.locator('.segment').nth(8).click();
  await page.waitForFunction(() => document.querySelector('.layer[data-layer="2"] .state').textContent === 'Playing', { timeout: 10000 });
  assert.match(await page.locator('.layer[data-layer="2"] .bars').textContent(), /1\/16 bar/);
  await page.screenshot({ path: new URL('../web/public/main-looper-live.png', import.meta.url).pathname, fullPage: true });
  assert.deepEqual(errors, []);
  const narrow = await browser.newPage({ viewport: { width: 900, height: 1100 } });
  await narrow.goto(`${process.env.MANIFOLD_SITE_URL ?? 'http://127.0.0.1:4173'}/main-looper.html`);
  const frame = await narrow.locator('#instrument-frame').boundingBox();
  const firstSegment = await narrow.locator('.segment').first().boundingBox();
  const lastSegment = await narrow.locator('.segment').last().boundingBox();
  assert.ok(firstSegment.x >= frame.x - 1);
  assert.ok(lastSegment.x + lastSegment.width <= frame.x + frame.width + 1);
  assert.ok(await narrow.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await narrow.screenshot({ path: new URL('../web/public/main-looper-narrow.png', import.meta.url).pathname, fullPage: true });
  console.log(`Main looper browser: four strips, first loop ${inferredTempo} BPM, Live/L1 Retro Cap, L1 Free Cap/STOP, Source waveform/tabs, traditional arm/fire, reverse scrub, session save/reopen, decoded file and Rust synth capture passed`);
} finally { await browser.close(); }
