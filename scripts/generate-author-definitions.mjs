import { writeGeneratedFile as writeFile } from './write-generated-file.mjs';
// Names describe the Rust contract; neither names nor exports implement DSP.
import { readFile } from 'node:fs/promises';
import { PORT_CATALOG } from '../packages/manifold-author/catalog.generated.js';
import { PARAMETER_NAMES } from '../packages/manifold-author/parameter-names.js';

const camel = type => type.replace(/[.-]([a-z])/g, (_, letter) => letter.toUpperCase());
const definitions = Object.keys(PORT_CATALOG).map(type => [camel(type), type]);
for (const [type, contract] of Object.entries(PORT_CATALOG)) {
  const names = PARAMETER_NAMES[type] ?? {};
  if (contract.parameters.length !== Object.keys(names).length
    || contract.parameters.some(parameter => !names[parameter.id])
    || new Set(Object.values(names)).size !== Object.keys(names).length) {
    throw new Error(`Incomplete or ambiguous author names: ${type}`);
  }
}
const header = '// Generated by scripts/generate-author-definitions.mjs.\n';
const files = {
  'primitives.js': header + "import { getPrimitive } from './index.js';\n\n" + definitions.map(([name, type]) => `export const ${name} = getPrimitive('${type}');`).join('\n') + '\n',
  'primitives.d.ts': header + "import type { AuthorPrimitive } from './index.js';\n\n" + definitions.map(([name, type]) => `export const ${name}: AuthorPrimitive<'${type}'>;`).join('\n') + '\n',
  'parameter-names.generated.d.ts': header + 'export interface NamedParameters {\n' + Object.entries(PARAMETER_NAMES).map(([type, names]) => `  '${type}': ${type === 'mixer' ? "'masterLevel' | `input${number}Gain` | `input${number}Pan`" : Object.values(names).map(name => `'${name}'`).join(' | ')};`).join('\n') + '\n}\n',
};
for (const [name, content] of Object.entries(files)) {
  const path = new URL('../packages/manifold-author/' + name, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`Stale author definitions: ${name}`);
  } else await writeFile(path, content);
}
