import {test} from 'node:test';
import assert from 'node:assert/strict';
import {LiveProjectRuntime} from '../../packages/manifold-author/live-project.js';
import {source} from '../../packages/manifold-author/examples/standalone-oscillator.mjs';
import {decodeMidiControl,AuthoredMidiInput} from '../../packages/manifold-author/midi-control.js';
test('event state waits for audio acknowledgement; MIDI velocity zero and pedal decode into authored events',async()=>{
  let accept;
  const runtime=new LiveProjectRuntime({ready:true,setParameterBatch:()=>new Promise(resolve=>{accept=resolve;})},source);
  const before=runtime.save();
  const pending=runtime.request({operation:'event.send',event:decodeMidiControl(new Uint8Array([0x92,60,90]),'device')});
  await new Promise(resolve=>setImmediate(resolve));
  assert.deepEqual(runtime.save(),before);
  accept(true);await pending;
  assert.equal(runtime.snapshot().eventState.voices[0].channel,2);
  assert.deepEqual(decodeMidiControl({0:0x92,1:60,2:0},'device'),{type:'note-off',note:60,channel:2,owner:'device'});
  assert.deepEqual(decodeMidiControl([0xb2,64,127],'device'),{type:'sustain',down:true,channel:2,owner:'device'});
  assert.equal(decodeMidiControl([0xf8]),null);
});
test('MIDI channel releases, pedal and disconnect preserve unrelated sounding ownership',async()=>{
  const runtime=new LiveProjectRuntime({ready:true,setParameterBatch:async()=>true},source);
  const send=event=>runtime.request({operation:'event.send',event});
  const midi=bytes=>send(decodeMidiControl(bytes,'device'));
  await send({type:'note-on',note:60,owner:'keyboard'});
  await midi([0x90,64,100]);await midi([0x91,67,100]);
  await midi([0xb0,64,127]);await midi([0xb0,123,0]);
  let voices=runtime.snapshot().eventState.voices;
  assert(voices.find(v=>v.note===64).gate); // all-notes-off respects pedal
  assert.equal(voices.find(v=>v.note===64).keyDown,0);
  await midi([0xb0,64,0]);
  voices=runtime.snapshot().eventState.voices;
  assert.equal(voices.find(v=>v.note===64).gate,0);
  assert(voices.find(v=>v.note===67).gate);
  await midi([0xb1,120,0]);
  assert(runtime.snapshot().eventState.voices.find(v=>v.note===60).gate);
  await midi([0x90,69,100]);
  await send({type:'panic',owner:'device'});
  assert.deepEqual(runtime.snapshot().eventState.voices.filter(v=>v.gate).map(v=>v.note),[60]);
  assert.equal(decodeMidiControl([0x90,60]),null);
  await send({type:'panic'});assert(runtime.snapshot().eventState.voices.every(v=>!v.gate));
});
test('public MIDI adapter releases only selected device and reports failed switches',async()=>{
  const events=[],statuses=[];
  let reject=false;
  const ports=new Map(['a','b'].map(id=>[id,{id,name:id,state:'connected',open:async()=>{},close:async()=>{}}]));
  const access={inputs:ports};
  const input=new AuthoredMidiInput(async event=>{if(reject)throw Error('Rejected');events.push(event);},s=>statuses.push(s));
  await input.connect(async()=>access);await input.select('a');
  ports.get('a').onmidimessage({data:[0x91,60,100]});
  await input.select('b');
  assert.deepEqual(events,[{type:'note-on',note:60,velocity:100,owner:'midi:a',channel:1},{type:'panic',owner:'midi:a'}]);
  reject=true;await assert.rejects(input.select('a'));assert.equal(input.input.id,'b');
  reject=false;ports.get('b').state='disconnected';access.onstatechange();
  await input.pending;assert.equal(input.input,null);
  assert.deepEqual(events.at(-1),{type:'panic',owner:'midi:b'});
  await input.disconnect();assert.equal(access.onstatechange,null);
});
